const hre = require("hardhat");
const fs = require("fs");
const path = require("path");

async function main() {
  console.log("=================================================================");
  console.log("       BlockLoan — Local Blockchain Deployment Pipeline         ");
  console.log("=================================================================");

  const networkName = hre.network.name;
  const chainId = hre.network.config.chainId || 31337;
  console.log(`Target Network : ${networkName} (Chain ID: ${chainId})`);

  const [deployer] = await hre.ethers.getSigners();
  console.log(`Deployer       : ${deployer.address}`);

  const balanceWei = await hre.ethers.provider.getBalance(deployer.address);
  console.log(`Balance        : ${hre.ethers.formatEther(balanceWei)} ETH`);

  console.log("\nDeploying BlockLoan.sol smart contract...");
  const BlockLoanFactory = await hre.ethers.getContractFactory("BlockLoan");
  const blockLoan = await BlockLoanFactory.deploy();
  await blockLoan.waitForDeployment();

  const contractAddress = await blockLoan.getAddress();
  console.log(`>>> BlockLoan Deployed At Address: ${contractAddress} <<<`);

  // Verify contract code exists at deployed address
  const code = await hre.ethers.provider.getCode(contractAddress);
  if (code === "0x") {
    throw new Error("Contract deployment failed: No runtime bytecode found at target address.");
  }
  console.log(`Bytecode Size  : ${(code.length - 2) / 2} bytes (Verified on-chain)`);

  // Read compiled artifact for ABI
  const artifactPath = path.join(
    __dirname,
    "..",
    "artifacts",
    "contracts",
    "BlockLoan.sol",
    "BlockLoan.json"
  );
  if (!fs.existsSync(artifactPath)) {
    throw new Error(`Artifact not found at ${artifactPath}. Please run 'npx hardhat compile' first.`);
  }
  const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));

  const deploymentData = {
    contractAddress: contractAddress,
    deployer: deployer.address,
    network: networkName,
    chainId: chainId,
    deployedAt: new Date().toISOString(),
    transactionHash: blockLoan.deploymentTransaction()?.hash || null,
    abi: artifact.abi,
  };

  // 1. Export to blockchain/deployments/
  const bcDeploymentsDir = path.join(__dirname, "..", "deployments");
  if (!fs.existsSync(bcDeploymentsDir)) {
    fs.mkdirSync(bcDeploymentsDir, { recursive: true });
  }
  const bcFile = path.join(bcDeploymentsDir, "localhost.json");
  fs.writeFileSync(bcFile, JSON.stringify(deploymentData, null, 2));
  console.log(`\n[Export 1] Blockchain deployment saved -> ${bcFile}`);

  // 2. Export to frontend/src/contracts/
  const frontendContractsDir = path.join(__dirname, "..", "..", "frontend", "src", "contracts");
  if (fs.existsSync(frontendContractsDir)) {
    const feFile = path.join(frontendContractsDir, "BlockLoan.json");
    fs.writeFileSync(feFile, JSON.stringify(deploymentData, null, 2));
    console.log(`[Export 2] Frontend JSON artifact saved -> ${feFile}`);

    const feConfigFile = path.join(frontendContractsDir, "contractConfig.ts");
    const tsContent = `// Auto-generated by BlockLoan deployment pipeline
// Do not edit manually. Generated at: ${deploymentData.deployedAt}

export const BLOCKLOAN_CONTRACT_ADDRESS = "${contractAddress}";
export const BLOCKLOAN_CHAIN_ID = ${chainId};
export const BLOCKLOAN_NETWORK_NAME = "Hardhat Local";
export const BLOCKLOAN_RPC_URL = "http://127.0.0.1:8545";

export const BLOCKLOAN_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;
    fs.writeFileSync(feConfigFile, tsContent);
    console.log(`[Export 3] Frontend contractConfig.ts updated -> ${feConfigFile}`);
  }

  // 3. Export to backend/deployments/
  const backendDeploymentsDir = path.join(__dirname, "..", "..", "backend", "deployments");
  if (!fs.existsSync(backendDeploymentsDir)) {
    fs.mkdirSync(backendDeploymentsDir, { recursive: true });
  }
  const backendFile = path.join(backendDeploymentsDir, "localhost.json");
  fs.writeFileSync(backendFile, JSON.stringify(deploymentData, null, 2));
  console.log(`[Export 4] Backend deployment artifact saved -> ${backendFile}`);

  console.log("\n=================================================================");
  console.log("            Deployment & ABI Synchronization Complete           ");
  console.log("=================================================================\n");
}

main().catch((error) => {
  console.error("\n[DEPLOYMENT ERROR]:", error.message || error);
  process.exitCode = 1;
});
